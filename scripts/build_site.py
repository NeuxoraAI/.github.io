#!/usr/bin/env python3
"""Deterministic static site generator and integrity verifier for Neuxora."""

from __future__ import annotations

import argparse
from html.parser import HTMLParser
from pathlib import Path
import sys
from urllib.parse import urlparse

ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

from src.data import SITE  # noqa: E402
from src.layout import render_page  # noqa: E402
from src.pages import PAGES  # noqa: E402

CSS_PARTS = [
    ROOT_DIR / "assets" / "css" / "01-tokens.css",
    ROOT_DIR / "assets" / "css" / "02-base-layout.css",
    ROOT_DIR / "assets" / "css" / "03-components.css",
    ROOT_DIR / "assets" / "css" / "04-interactive.css",
    ROOT_DIR / "assets" / "css" / "05-cosmos.css",
]
CSS_OUT = ROOT_DIR / "assets" / "neuxora.css"
SITEMAP_OUT = ROOT_DIR / "sitemap.xml"
SITEMAP_LASTMOD = "2026-11-15"


class _DocumentInspector(HTMLParser):
    """Lightweight HTML structural & reference collector."""

    def __init__(self) -> None:
        super().__init__()
        self.ids: set[str] = set()
        self.duplicate_ids: list[str] = []
        self.refs: list[tuple[str, str]] = []
        self.has_title = False
        self.has_description = False
        self.has_main = False
        self.has_footer = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attr_map = {k: (v or "") for k, v in attrs}
        if "id" in attr_map and attr_map["id"]:
            elem_id = attr_map["id"]
            if elem_id in self.ids:
                self.duplicate_ids.append(elem_id)
            self.ids.add(elem_id)

        if tag == "title":
            self.has_title = True
        elif tag == "meta" and attr_map.get("name") == "description" and attr_map.get("content"):
            self.has_description = True
        elif tag == "main" and attr_map.get("id") == "main":
            self.has_main = True
        elif tag == "footer" and "footer" in attr_map.get("class", "").split():
            self.has_footer = True

        if tag in ("a", "link") and attr_map.get("href"):
            self.refs.append((tag, attr_map["href"]))
        elif tag in ("script", "img") and attr_map.get("src"):
            self.refs.append((tag, attr_map["src"]))


def build_css() -> str:
    """Concatenate layered CSS source files into production stylesheet."""
    header = (
        "/* AUTO-GENERATED by scripts/build_site.py from assets/css/*.css — DO NOT EDIT DIRECTLY */\n\n"
    )
    chunks = [part.read_text(encoding="utf-8").strip() for part in CSS_PARTS]
    return header + "\n\n".join(chunks) + "\n"


def build_sitemap() -> str:
    """Generate deterministic XML sitemap from page registry."""
    base = SITE["base_url"].rstrip("/")
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for page in PAGES:
        if not page.get("include_in_sitemap", True):
            continue
        loc = f"{base}/" if page["slug"] == "index.html" else f"{base}/{page['slug']}"
        lines.append(f"  <url><loc>{loc}</loc><lastmod>{SITEMAP_LASTMOD}</lastmod></url>")
    lines.append("</urlset>\n")
    return "\n".join(lines)


def build_outputs() -> dict[Path, str]:
    """Compute all target files and their expected UTF-8 contents."""
    outputs: dict[Path, str] = {
        CSS_OUT: build_css(),
        SITEMAP_OUT: build_sitemap(),
    }
    for page in PAGES:
        body_html = page["renderer"]()
        rendered = render_page(
            title=page["title"],
            description=page["description"],
            slug=page["slug"],
            active_key=page["active_key"],
            body_html=body_html,
            og_type=page.get("og_type", "website"),
            robots=page.get("robots", "index, follow"),
            extra_head=page.get("extra_head", ""),
        )
        outputs[ROOT_DIR / page["slug"]] = rendered
    return outputs


def validate_outputs(outputs: dict[Path, str]) -> list[str]:
    """Validate generated HTML documents, internal links, anchors, and synchronization."""
    errors: list[str] = []
    inspectors: dict[str, _DocumentInspector] = {}

    for path, expected in outputs.items():
        if not path.exists():
            errors.append(f"Missing generated file: {path.relative_to(ROOT_DIR)}")
        else:
            actual = path.read_text(encoding="utf-8")
            if actual != expected:
                errors.append(f"Out-of-sync generated file: {path.relative_to(ROOT_DIR)} (run build_site.py)")

        if path.suffix == ".html":
            inspector = _DocumentInspector()
            inspector.feed(expected)
            slug = path.name
            inspectors[slug] = inspector

            if not inspector.has_title:
                errors.append(f"{slug}: missing <title>")
            if not inspector.has_description:
                errors.append(f"{slug}: missing <meta name='description'>")
            if not inspector.has_main:
                errors.append(f"{slug}: missing <main id='main'>")
            if not inspector.has_footer:
                errors.append(f"{slug}: missing <footer class='footer'>")
            for dup_id in inspector.duplicate_ids:
                errors.append(f"{slug}: duplicate element id '{dup_id}'")

    for slug, inspector in inspectors.items():
        for tag, ref in inspector.refs:
            if ref.startswith(("http://", "https://", "mailto:", "tel:")):
                continue
            if ref.startswith("#"):
                anchor = ref[1:]
                if anchor and anchor not in inspector.ids:
                    errors.append(f"{slug}: broken same-page anchor '#{anchor}'")
                continue

            parsed = urlparse(ref)
            rel_path = parsed.path
            target_file = ROOT_DIR / rel_path
            if not target_file.exists():
                errors.append(f"{slug}: broken internal {tag} reference '{ref}'")
                continue

            if parsed.fragment and target_file.suffix == ".html":
                target_inspector = inspectors.get(target_file.name)
                if target_inspector and parsed.fragment not in target_inspector.ids:
                    errors.append(f"{slug}: missing target anchor '{parsed.fragment}' in '{rel_path}'")

    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description="Build or validate Neuxora static site.")
    parser.add_argument("--check", action="store_true", help="Verify generated files and links without writing.")
    args = parser.parse_args()

    outputs = build_outputs()

    if args.check:
        errors = validate_outputs(outputs)
        if errors:
            for err in errors:
                print(f"ERROR: {err}", file=sys.stderr)
            return 1
        print(f"OK: {len(outputs)} generated files synchronized and all internal links/anchors verified.")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT_DIR)}")

    errors = validate_outputs(outputs)
    if errors:
        for err in errors:
            print(f"ERROR: {err}", file=sys.stderr)
        return 1

    print(f"Done: built and verified {len(outputs)} artifacts.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
